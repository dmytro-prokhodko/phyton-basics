#створюємо сітку матрицб з нулів
grid = [
    [0, 0, 0],
    [0, 0, 0],
    [0, 0, 0]
]

#змінюємо центр
#другий рядок (1), другий елемент (1)
grid[1][1] = 1

print("сітка з ввімкненим центром:")

#виводимо матрицю квадратом
for row in grid:             #зовнішній цикл: беремо по черзі кожен рядок
    for item in row:         #внутрішній цикл: беремо кожне число в рядку
        print(item, end=" ") #друкує число і додає пробіл замість переносу рядка
    print() #переносить на наступний рядок